#!/usr/bin/env python3
"""
Builds the project-catalogue load files from catalogue.py.

Output (this folder):
  load_catalogue.sql      - archives the old active projects (remembering their status)
                            and adds the 40 projects linked to the audited inventory
  rollback_catalogue.sql  - puts the previous catalogue back
  catalogue.json          - the full dataset, for review
  COMPONENT_REPORT.md     - per-project components, stock at audit time, external items
Run: python3 generate.py
"""
import csv
import json
from pathlib import Path

from catalogue import PROJECTS

HERE = Path(__file__).resolve().parent
BATCH = 'project-catalogue-2026-10'
ROLLED_BACK = f'{BATCH}:rolled-back'   # project_status_backup batch written by the rollback, read by the next load
AUDIT ='components-audit-2026-10-12'
AUDIT_CSV = HERE.parent / 'components_audit_2026-10-12' / 'dataset.csv'

audit = {}
for r in csv.DictReader(open(AUDIT_CSV, encoding='utf-8')):
    key = ('S' if r['source_section'] == 'special_equipment' else 'C') + r['source_row']
    audit[key] = r

# ---------------------------------------------------------------- validation
problems = []
for p in PROJECTS:
    keys = [c[0] for c in p['components']]
    if len(keys) != len(set(keys)):
        problems.append(f"{p['n']} {p['name']}: duplicate component")
    for key, qty, _ in p['components']:
        if key not in audit:
            problems.append(f"{p['n']} {p['name']}: unknown audit row {key}")
        if not (1 <= qty <= 1000):
            problems.append(f"{p['n']} {p['name']}: bad quantity for {key}")
    if not p['components']:
        problems.append(f"{p['n']} {p['name']}: no components")
    lo, hi = p['hours']
    if lo > hi:
        problems.append(f"{p['n']} {p['name']}: hours")
if problems:
    raise SystemExit('\n'.join(problems))


def q(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (list, tuple)):
        return ('array[' + ', '.join(q(x) for x in v) + ']::text[]') if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def ckey(p):
    return f'{BATCH}:{p["n"]:02d}'


def status_at_audit(p):
    """Availability using the audit's available figures (live status is computed by the database)."""
    sat = sum(1 for k, qty, _ in p['components'] if int(audit[k]['proposed_available']) >= qty)
    n = len(p['components'])
    if p['verification']:
        return 'requires_verification'
    if sat == n:
        return 'requires_external' if p['external'] else 'available'
    return 'partially_available' if sat else 'temporarily_unavailable'


# ---------------------------------------------------------------- load SQL
proj_rows = []
for p in PROJECTS:
    instructions = '\n\n'.join(f'{i}. {s}' for i, s in enumerate(p['steps'], 1))
    vals = [ckey(p), p['name'], p['slug'], p['category'], p['difficulty'], p['hours'][0], p['hours'][1],
            p['description'], instructions, p['objectives'], p['objectives'], p['prerequisites'], p['hardware_software'],
            p['outcome'], p['testing'], p['safety'], p['extensions'], p['external'], p['verification'],
            f'/projects/{p["slug"]}.svg', p['image_alt']]
    proj_rows.append('  (' + ', '.join(q(v) for v in vals) + ')')

comp_rows = []
for p in PROJECTS:
    for key, qty, note in p['components']:
        section = 'special_equipment' if key[0] == 'S' else 'small_components'
        comp_rows.append(f"  ({q(ckey(p))}, {q(section)}, {int(key[1:])}, {qty}, {q(note)})")

load = f"""-- =============================================================================
-- Replace the active project catalogue with the ISD Lab catalogue (Oct 2026, 40 projects).
-- GENERATED by supabase/import/project_catalogue_2026-10/generate.py - edit catalogue.py instead.
--
-- Requires migrations 0001-0009 and the applied COMPONENTS Audit (inventory items are
-- found through inventory_source_records, so the live inventory IDs are used and no
-- inventory item is created or changed).
--
--   1. Every active project that is not part of this catalogue is ARCHIVED (never deleted);
--      its previous status is saved in project_status_backup for rollback_catalogue.sql.
--      Requests and history that reference old projects are untouched.
--   2. The 40 projects are inserted as drafts, their components linked, then published.
--   3. Re-running while the catalogue is live only adds catalogue projects that are missing:
--      it archives nothing and leaves projects and requirements edited in the app alone.
--      After rollback_catalogue.sql it replaces the active catalogue again and gives every
--      catalogue project back the status it had before the rollback.
-- =============================================================================
begin;

select set_config('request.jwt.claim.sub',
  (select id::text from public.profiles where role in ('admin', 'super_admin') and status = 'active' order by created_at limit 1), true);
select set_config('request.jwt.claims',
  json_build_object('sub', current_setting('request.jwt.claim.sub', true), 'role', 'authenticated')::text, true);

do $$
begin
  if (select count(*) from public.inventory_source_records
       where batch_key = '{AUDIT}' and status = 'applied') = 0 then
    raise exception 'Apply the COMPONENTS Audit to the inventory first (no applied audit rows found).';
  end if;
end $$;

-- Replace the active catalogue only on the first load, or after rollback_catalogue.sql (which leaves
-- a '{ROLLED_BACK}' row per catalogue project). Otherwise the catalogue is already live.
create temp table _catalogue_run on commit drop as
select not exists (select 1 from public.projects where catalogue_key like '{BATCH}:%')
       or exists (select 1 from public.project_status_backup where batch_key = '{ROLLED_BACK}') as replace_active;
create temp table _catalogue_new (id uuid primary key) on commit drop;

-- 1. Archive the old active catalogue (reversible).
insert into public.project_status_backup (batch_key, project_id, previous_status)
select '{BATCH}', p.id, p.status from public.projects p
 where (select replace_active from _catalogue_run)
   and p.status <> 'archived' and (p.catalogue_key is null or p.catalogue_key not like '{BATCH}:%')
on conflict do nothing;
update public.projects set status = 'archived'
 where (select replace_active from _catalogue_run)
   and status <> 'archived' and (catalogue_key is null or catalogue_key not like '{BATCH}:%');

-- 2. Projects (remembering which ones this run inserted).
with v (catalogue_key, name, slug, category, difficulty, est_hours_min, est_hours_max, description, instructions,
        learning_outcomes, objectives, prerequisites, hardware_software, expected_outcome, testing_steps,
        safety_notes, extensions, external_requirements, verification_note, image_path, image_alt) as (
values
{(',' + chr(10)).join(proj_rows)}
), inserted as (
insert into public.projects (catalogue_key, name, slug, category, difficulty, est_hours_min, est_hours_max, description,
  instructions, learning_outcomes, objectives, prerequisites, hardware_software, expected_outcome, testing_steps,
  safety_notes, extensions, external_requirements, verification_note, image_path, image_alt, status, is_demo)
select v.catalogue_key, v.name,
       case when exists (select 1 from public.projects o where o.slug = v.slug) then v.slug || '-isd' else v.slug end,
       v.category, v.difficulty::public.project_difficulty, v.est_hours_min, v.est_hours_max, v.description, v.instructions,
       v.learning_outcomes, v.objectives, v.prerequisites, v.hardware_software, v.expected_outcome, v.testing_steps,
       v.safety_notes, v.extensions, v.external_requirements, v.verification_note, v.image_path, v.image_alt, 'draft', false
  from v
on conflict (catalogue_key) do nothing
returning id
)
insert into _catalogue_new (id) select id from inserted;

-- 3. Required components, linked to the audited inventory items.
with c (catalogue_key, source_section, source_row, qty, notes) as (
values
{(',' + chr(10)).join(comp_rows)}
)
insert into public.project_components (project_id, item_id, qty_required, notes)
select p.id, s.item_id, c.qty, c.notes
  from c
  join public.projects p on p.catalogue_key = c.catalogue_key
  join public.inventory_source_records s
    on s.batch_key = '{AUDIT}' and s.source_section = c.source_section
   and s.source_row = c.source_row and s.status = 'applied' and s.item_id is not null
 where p.id in (select id from _catalogue_new)   -- only projects inserted by this run; existing ones keep any admin edits
on conflict (project_id, item_id) do nothing;

-- 4. Publish the new projects that have their components.
update public.projects p set status = 'published'
 where p.id in (select id from _catalogue_new)
   and exists (select 1 from public.project_components pc where pc.project_id = p.id);

-- 5. After a rollback: give each catalogue project the status it had before the rollback (so one an
--    admin had unpublished or archived stays that way), unless it was changed since.
update public.projects p set status = b.previous_status
  from public.project_status_backup b
 where b.batch_key = '{ROLLED_BACK}' and b.project_id = p.id and p.status = 'draft'
   and (b.previous_status <> 'published'
        or exists (select 1 from public.project_components pc where pc.project_id = p.id));
delete from public.project_status_backup where batch_key = '{ROLLED_BACK}';

commit;

-- Check: 40 published catalogue projects, nothing else active.
select case when catalogue_key like '{BATCH}:%' then 'new catalogue' else 'other' end as source,
       status, count(*) from public.projects group by 1, 2 order by 1, 2;
"""
(HERE / 'load_catalogue.sql').write_text(load, encoding='utf-8')

rollback = f"""-- Undo load_catalogue.sql: hide the {len(PROJECTS)} catalogue projects (as drafts) and restore
-- every project to the status it had before. Nothing is deleted.
begin;
select set_config('request.jwt.claim.sub',
  (select id::text from public.profiles where role in ('admin', 'super_admin') and status = 'active' order by created_at limit 1), true);
select set_config('request.jwt.claims',
  json_build_object('sub', current_setting('request.jwt.claim.sub', true), 'role', 'authenticated')::text, true);

-- Remember each catalogue project's status, so re-running load_catalogue.sql puts back exactly that
-- (a project an admin had unpublished or archived stays so). A second rollback keeps the first record.
insert into public.project_status_backup (batch_key, project_id, previous_status)
select '{ROLLED_BACK}', p.id, p.status from public.projects p where p.catalogue_key like '{BATCH}:%'
on conflict do nothing;

-- Catalogue projects become drafts (hidden from students); re-running load_catalogue.sql publishes them again.
update public.projects set status = 'draft' where catalogue_key like '{BATCH}:%' and status <> 'draft';
update public.projects p set status = b.previous_status
  from public.project_status_backup b
 where b.batch_key = '{BATCH}' and b.project_id = p.id
   and (b.previous_status <> 'published'
        or exists (select 1 from public.project_components pc where pc.project_id = p.id));
delete from public.project_status_backup where batch_key = '{BATCH}';
commit;
select status, count(*) from public.projects group by 1;
"""
(HERE / 'rollback_catalogue.sql').write_text(rollback, encoding='utf-8')

# ---------------------------------------------------------------- dataset + report
out = []
for p in PROJECTS:
    d = dict(p)
    d['catalogue_key'] = ckey(p)
    d['image_path'] = f'/projects/{p["slug"]}.svg'
    d['components'] = [{'audit_row': k, 'item': audit[k]['display_name'], 'qty': qty, 'note': note,
                        'available_at_audit': int(audit[k]['proposed_available']),
                        'borrowable': audit[k]['proposed_requestable'] == 'True'} for k, qty, note in p['components']]
    d['status_at_audit'] = status_at_audit(p)
    out.append(d)
(HERE / 'catalogue.json').write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding='utf-8')

LABEL = {'available': 'Available to build', 'requires_external': 'Requires external components',
         'partially_available': 'Partially available', 'temporarily_unavailable': 'Temporarily unavailable',
         'requires_verification': 'Requires compatibility verification'}
from collections import Counter
counts = Counter(d['status_at_audit'] for d in out)
lines = [f'# Project catalogue (Oct 2026) - component report', '',
         'Availability below uses the audit figures of 12/10/2026. In the app it is calculated live from current stock,',
         'so it changes as items are borrowed, returned, damaged or re-counted.', '',
         '| Status | Projects |', '|---|---|'] + [f'| {LABEL[k]} | {v} |' for k, v in counts.most_common()] + ['']
for d in out:
    lines += [f'## {d["n"]}. {d["name"]} - {LABEL[d["status_at_audit"]]}', '',
              f'{d["category"]} · {d["difficulty"]} · {d["hours"][0]}-{d["hours"][1]} h', '',
              '| Audit item | Qty | Available at audit | Borrowable |', '|---|---|---|---|']
    lines += [f'| {c["item"]} | {c["qty"]} | {c["available_at_audit"]} | {"yes" if c["borrowable"] else "lab use only"} |' for c in d['components']]
    if d['external']:
        lines += ['', 'Not stocked by the lab: ' + '; '.join(d['external'])]
    if d['verification']:
        lines += ['', 'Needs verification: ' + d['verification']]
    lines.append('')
(HERE / 'COMPONENT_REPORT.md').write_text('\n'.join(lines), encoding='utf-8')
print(dict(counts), 'components:', sum(len(p['components']) for p in PROJECTS))
