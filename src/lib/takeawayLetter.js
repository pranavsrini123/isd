// Component take-away permission letter (A4, printable, signed by hand).
// Built only from get_takeaway_letter(), which refuses anything that is not
// approved, so an unapproved request can never produce a letter in the app.
import { A4, PdfDocument, wrapText } from './pdf'

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
const IST_OFFSET_MIN = 330 // the lab runs on India Standard Time

/** "29 Oct 2026" from 'YYYY-MM-DD' (taken as written) or a timestamp (shown in IST). */
export function letterDate(value) {
  if (!value) return ''
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value)
  if (m) return `${Number(m[3])} ${MONTHS[Number(m[2]) - 1]} ${m[1]}`
  const d = new Date(new Date(value).getTime() + IST_OFFSET_MIN * 60000)
  if (Number.isNaN(d.getTime())) return ''
  return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`
}

/** "29 Oct 2026, 14:05 IST" from a timestamp. */
export function letterDateTime(value) {
  const d = new Date(new Date(value).getTime() + IST_OFFSET_MIN * 60000)
  if (Number.isNaN(d.getTime())) return ''
  const p2 = (n) => String(n).padStart(2, '0')
  return `${letterDate(value)}, ${p2(d.getUTCHours())}:${p2(d.getUTCMinutes())} IST`
}

/** True when the data describes an approved request (the database already refuses others). */
export function isLetterAllowed(data) {
  return !!data && (data.status === 'approved' || data.status === 'submitted') && !!data.approved_by && !!data.approved_at
}

export function letterFileName(data) {
  return `${data.request_code}-permission-letter.pdf`
}

const INK = [0.043, 0.075, 0.141]     // #0B1324
const MUTED = [0.32, 0.376, 0.475]    // #526079
const NAVY = [0.027, 0.051, 0.122]    // #070D1F
const BRAND = [0.055, 0.455, 0.565]   // #0E7490
const LINE = [0.8, 0.835, 0.882]      // #CBD5E1
const TINT = [0.945, 0.961, 0.98]     // #F1F5FA

/**
 * Lays out the letter and returns the PDF bytes.
 * data: the JSON returned by get_takeaway_letter().
 */
export function buildTakeawayLetter(data, { now = new Date() } = {}) {
  if (!isLetterAllowed(data)) throw new Error('A permission letter is only available after Super Admin approval.')
  const doc = new PdfDocument({
    title: `Permission to take components outside the lab - ${data.request_code}`,
    author: 'INVENTRA - ISD Lab',
    subject: 'Component take-away permission letter',
  })
  const L = 56
  const R = A4.width - 56
  const W = R - L
  const BOTTOM = A4.height - 58
  let y = 0
  let page = 1

  const footer = () => {
    doc.line(L, A4.height - 46, R, A4.height - 46, { width: 0.5, color: LINE })
    doc.text(L, A4.height - 32, `Generated by INVENTRA on ${letterDateTime(now)} · Ref. ${data.request_code}. Staff can verify this reference in INVENTRA.`, { size: 7.5, color: MUTED })
    doc.text(R, A4.height - 32, `Page ${page}`, { size: 7.5, color: MUTED, align: 'right' })
  }
  const header = (continued) => {
    doc.rect(0, 0, A4.width, 6, { fill: BRAND })
    doc.text(L, 40, 'INVENTRA', { size: 15, font: 'bold', color: NAVY })
    doc.text(L + 82, 40, 'by ISD Lab', { size: 9, color: BRAND })
    doc.text(L, 55, 'Intelligent Systems Design Lab', { size: 9, color: MUTED })
    doc.text(L, 67, 'SRM Institute of Science and Technology, Kattankulathur', { size: 9, color: MUTED })
    doc.text(R, 40, `Ref. ${data.request_code}`, { size: 10, font: 'bold', color: INK, align: 'right' })
    doc.text(R, 55, `Date: ${letterDate(data.approved_at)}`, { size: 9, color: MUTED, align: 'right' })
    if (continued) doc.text(R, 67, '(continued)', { size: 9, color: MUTED, align: 'right' })
    doc.line(L, 80, R, 80, { width: 0.75, color: LINE })
    y = 104
  }
  const ensure = (h) => {
    if (y + h <= BOTTOM) return
    footer()
    doc.addPage()
    page += 1
    header(true)
  }
  const heading = (t) => {
    ensure(30)
    doc.text(L, y, t.toUpperCase(), { size: 8.5, font: 'bold', color: BRAND })
    y += 14
  }

  header(false)

  // Addressee and subject
  doc.text(L, y, 'To', { size: 10, color: INK }); y += 14
  doc.text(L, y, 'The Chairperson and the Associate Chairperson', { size: 10, color: INK }); y += 14
  doc.text(L, y, 'ISD Lab, SRM Institute of Science and Technology, Kattankulathur', { size: 10, color: INK }); y += 20
  doc.text(L, y, 'Subject:', { size: 10.5, font: 'bold', color: INK })
  y = doc.paragraph(L + 50, y, 'Permission to take laboratory components / equipment outside the ISD Lab', W - 50, { size: 10.5, font: 'bold', color: INK }) + 6

  doc.text(L, y, 'Respected Sir / Madam,', { size: 10, color: INK }); y += 18
  y = doc.paragraph(L, y,
    `I, ${data.student_name} (Register No. ${data.registration_number}), ${data.department}, request permission to take the `
    + 'components listed below outside the ISD Lab for the purpose stated in this letter. I will keep them safe, use them only '
    + 'for this purpose, and return them to the lab in the same condition'
    + (data.expected_return_date ? ` by ${letterDate(data.expected_return_date)}.` : '.'),
    W, { size: 10, color: INK }) + 4

  // Student details
  // Two columns of label / value pairs.
  const pairs = (list) => {
    const half = W / 2
    for (let i = 0; i < list.length; i += 2) {
      ensure(16)
      list.slice(i, i + 2).forEach(([k, v], c) => {
        const x = L + c * half
        doc.text(x, y, k, { size: 9, color: MUTED })
        const val = wrapText(v || '', half - 112, 9.5, 'bold')[0] || ''
        doc.text(x + 100, y, val, { size: 9.5, color: INK, font: 'bold' })
      })
      y += 15
    }
  }
  heading('Student details')
  pairs([
    ['Name', data.student_name],
    ['Register number', data.registration_number],
    ['Email ID', data.email],
    ['Department', data.department],
  ])
  y += 6

  // Components table
  heading('Components / equipment')
  const cols = [L, L + 28, R - 60]
  const rowH = 18
  ensure(rowH * 2)
  doc.rect(L, y - 12, W, rowH, { fill: TINT })
  doc.text(cols[0] + 6, y, '#', { size: 8.5, font: 'bold', color: MUTED })
  doc.text(cols[1], y, 'Component', { size: 8.5, font: 'bold', color: MUTED })
  doc.text(R - 8, y, 'Quantity', { size: 8.5, font: 'bold', color: MUTED, align: 'right' })
  y += rowH
  ;(data.items || []).forEach((it, i) => {
    const label = it.brand_model ? `${it.name} (${it.brand_model})` : it.name
    const lines = wrapText(label, cols[2] - cols[1] - 8, 9.5)
    const h = Math.max(rowH, lines.length * 12 + 6)
    ensure(h)
    lines.forEach((ln, k) => doc.text(cols[1], y + k * 12, ln, { size: 9.5, color: INK }))
    doc.text(cols[0] + 6, y, String(i + 1), { size: 9.5, color: MUTED })
    doc.text(R - 8, y, String(it.qty), { size: 9.5, font: 'bold', color: INK, align: 'right' })
    doc.line(L, y + h - 12, R, y + h - 12, { width: 0.4, color: LINE })
    y += h
  })
  y += 10

  // Purpose and dates
  heading('Purpose')
  for (const ln of wrapText(data.purpose, W, 10)) { ensure(15); doc.text(L, y, ln, { size: 10, color: INK }); y += 14.5 }
  y += 6
  heading('Dates')
  pairs([
    ['Take-away date', letterDate(data.takeaway_date)],
    ['Expected return', data.expected_return_date ? letterDate(data.expected_return_date) : 'Not applicable'],
  ])
  y += 6
  if (data.additional_info) {
    heading('Additional information')
    for (const ln of wrapText(data.additional_info, W, 10)) { ensure(15); doc.text(L, y, ln, { size: 10, color: INK }); y += 14.5 }
    y += 6
  }

  // Approval record
  const approval = `Request ${data.request_code} was submitted on ${letterDate(data.submitted_at)} and approved in INVENTRA by `
    + `${data.approved_by} (Super Admin) on ${letterDateTime(data.approved_at)}.`
    + (data.approval_note ? ` Note: ${data.approval_note}` : '')
  const apLines = wrapText(approval, W - 24, 9.5)
  const apH = apLines.length * 13.5 + 40
  ensure(apH + 8)
  doc.rect(L, y - 4, W, apH, { fill: TINT, stroke: LINE, width: 0.6 })
  doc.text(L + 12, y + 12, 'APPROVAL RECORD', { size: 8.5, font: 'bold', color: BRAND })
  apLines.forEach((ln, k) => doc.text(L + 12, y + 28 + k * 13.5, ln, { size: 9.5, color: INK }))
  y += apH + 10
  ensure(30)
  y = doc.paragraph(L, y, 'This letter grants permission only when it is signed below by the Chairperson and the Associate Chairperson '
    + 'and the signed copy is handed to the ISD Lab admin.', W, { size: 9, color: MUTED }) + 14

  // Signatures (kept together on one page)
  ensure(118)
  const colW = (W - 30) / 2
  ;[['Chairperson', L], ['Associate Chairperson', L + colW + 30]].forEach(([title, x]) => {
    let yy = y
    doc.text(x, yy, title, { size: 11, font: 'bold', color: INK }); yy += 36
    for (const label of ['Signature', 'Name', 'Date']) {
      doc.text(x, yy, `${label}:`, { size: 9.5, color: MUTED })
      doc.line(x + 58, yy + 2, x + colW, yy + 2, { width: 0.6, color: INK })
      yy += 28
    }
  })
  y += 118

  footer()
  return doc.toBytes(now)
}
